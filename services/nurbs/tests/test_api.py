def test_submit_poll_result_real_step_end_to_end():
    """The headline test: submit → poll → fetch a REAL OCCT-produced STEP through the injected fit_fn
    (not a stub). Gated on pythonocc."""
    pytest.importorskip("OCC.Core.Geom")
    from app.occ_step import surfaces_json_to_step

    def real_fit_fn(payload: dict) -> dict:
        # A valid §6.2 bicubic patch (5×5 poles, one interior knot ⇒ a genuine multi-span B-spline,
        # not a Bézier-degenerate single span) driven through the REAL JSON→OCCT→STEP conversion.
        n = 5
        poles = [
            [
                [
                    i / (n - 1),
                    j / (n - 1),
                    0.2 * (1 - (2 * i / (n - 1) - 1) ** 2) * (1 - (2 * j / (n - 1) - 1) ** 2),
                ]
                for j in range(n)
            ]
            for i in range(n)
        ]
        surfaces = {
            "surfaces": [
                {
                    "poles": poles,
                    "weights": [],
                    "u_knots": [0.0, 0.5, 1.0],
                    "v_knots": [0.0, 0.5, 1.0],
                    "u_mults": [4, 1, 4],
                    "v_mults": [4, 1, 4],
                    "u_degree": 3,
                    "v_degree": 3,
                    "u_periodic": False,
                    "v_periodic": False,
                }
            ]
        }
        step, faces = surfaces_json_to_step(surfaces)
        report = {
            "patches": faces,
            "fitted_patches": faces,
            "faceted_patches": 0,
            "control_points": n * n,
            "degree_u": 3,
            "degree_v": 3,
            "iters": payload["iters"],
            "chamfer": 0.0,
            "scd": 0.0,
            "rms_deviation": 0.0,
            "max_deviation": 0.0,
            "fidelity_tol": payload["fidelity_tol"],
            "is_solid": False,
            "is_valid": True,
            "mode": payload["mode"],
        }
        return {"step": step, "surfaces": surfaces, "report": report}

    app = create_app(real_fit_fn)

    async def run():
        async with _client(app) as c:
            r = await c.post("/fit", json=_body(iters=200, mode="auto"))
            assert r.status_code == 200, r.text
            assert r.json()["state"] in ("queued", "running")
            job_id = r.json()["id"]

            state = await _drain(c, job_id, tries=1500, delay=0.05)
            status = (await c.get(f"/jobs/{job_id}/status")).json()
            assert state == "completed", f"job ended in {state}: {status}"

            result = await c.get(f"/jobs/{job_id}/result")
            assert result.status_code == 200, result.text
            body = result.json()
            # Real STEP text from OCCT.
            assert "B_SPLINE_SURFACE_WITH_KNOTS" in body["step"]
            # `surfaces` is the nested Surfaces object {"surfaces": [...]}, not a bare list (§6.2).
            assert body["surfaces"]["surfaces"], "result.surfaces must be the nested Surfaces object"
            # The full FR-9 report shape.
            assert set(body["report"].keys()) == FR9_REPORT_KEYS
            # The request body flowed through fit_fn.
            assert body["report"]["iters"] == 200
            assert body["report"]["mode"] == "auto"
            assert body["report"]["control_points"] == 25

    asyncio.run(run())


