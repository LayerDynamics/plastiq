def test_result_before_done_returns_409():
    release = threading.Event()
    app = create_app(_make_gated_fit_fn(release))

    async def run():
        async with _client(app) as c:
            try:
                job_id = (await c.post("/fit", json=_body())).json()["id"]
                # The job is gated open — it cannot complete until we set the event, so /result is 409.
                r = await c.get(f"/jobs/{job_id}/result")
                assert r.status_code == 409, r.text
            finally:
                release.set()
                await _drain(c, job_id)

    asyncio.run(run())


