def test_real_blob_closed_default_grid_end_to_end():
    """The served §6.1 DEFAULT closes: blob.glb (closed) with NO ``grid`` override — so FitBody's
    default grid=16 binds — → a watertight 6-patch NURBS solid through the LIVE service.

    The other closed E2E pins grid=8 (the proven pipeline gate); this pins the served default so a
    regression in FitBody's ``grid`` default (16 → anything) is caught. grid=16 closure is sound per
    SPEC-12 §8 U7 (holds at grid 8/12/16). ``iters=0`` (closed mode records but does not apply iters);
    no mocks — the production dispatcher runs the real closed pipeline + real OCCT sew/solid checks."""
    pytest.importorskip("mlx.core")
    pytest.importorskip("trimesh")
    pytest.importorskip("OCC.Core.Geom")

    app = create_app(_load_pipeline_fit)

    async def run():
        async with _client(app) as c:
            # No grid override → the request binds FitBody's default grid=16 (the served §6.1 default).
            r = await c.post("/fit", json=_glb_body("blob.glb", mode="auto", iters=0))
            assert r.status_code == 200, r.text
            job_id = r.json()["id"]

            state = await _drain(c, job_id, tries=2000, delay=0.05)
            status = (await c.get(f"/jobs/{job_id}/status")).json()
            assert state == "completed", f"blob job (default grid) ended in {state}: {status}"

            result = await c.get(f"/jobs/{job_id}/result")
            assert result.status_code == 200, result.text
            report = result.json()["report"]
            # The default grid=16 still closes into a watertight solid (SPEC-12 §8 U7), verified from
            # OCCT — never assumed.
            assert report["mode"] == "closed"
            assert report["is_solid"] is True, "default grid=16 did not close into a watertight solid"
            assert report["free_edges"] == 0
            assert report["fitted_patches"] == 6
            # Pin the grid actually used: 6 patches × a 16×16 control net (control_points scales with
            # grid). This is what makes the served default GRID=16 regression-caught — is_solid /
            # free_edges / fitted_patches alone also hold at the grid=8 sibling, so a 16→8 (or 16→12)
            # default regression would pass those but change control_points here and fail.
            assert report["control_points"] == 6 * 16 * 16  # 1536

    asyncio.run(run())
