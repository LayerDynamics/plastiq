def test_real_dome_mode_mismatch_fails_clean_500():
    """A VALID mesh with the WRONG explicit mode fails cleanly through the LIVE service: dome.glb
    (open) forced ``mode="closed"`` hits ``detect_mode``'s ``topology.mode != requested`` branch
    (distinct from the torus genus-raise and the ``mode="spline"`` 422) → job ``failed`` → /result
    500 surfacing the mismatch — and /health stays 200. ``iters=0`` (the mismatch raises before any
    fit, so no refine runs regardless)."""
