def test_auth_bearer_guards_fit_and_delete(monkeypatch):
    # NURBS_API_KEY set ⇒ POST /fit and DELETE require the bearer; 401 without, 200/204 with.
    monkeypatch.setenv("NURBS_API_KEY", "s3cret")
    app = create_app(_contract_result)
    auth = {"Authorization": "Bearer s3cret"}

    async def run():
        async with _client(app) as c:
            assert (await c.post("/fit", json=_body())).status_code == 401  # no header
            assert (
                await c.post("/fit", json=_body(), headers={"Authorization": "Bearer wrong"})
            ).status_code == 401  # wrong key
            r = await c.post("/fit", json=_body(), headers=auth)
            assert r.status_code == 200, r.text  # correct key
            job_id = r.json()["id"]
            # /health and reads stay open; only the mutating endpoints are guarded.
            assert (await c.get("/health")).status_code == 200
            assert (await c.get(f"/jobs/{job_id}/status")).status_code == 200
            assert (await c.delete(f"/jobs/{job_id}")).status_code == 401  # DELETE guarded too
            assert (await c.delete(f"/jobs/{job_id}", headers=auth)).status_code == 204

    asyncio.run(run())


