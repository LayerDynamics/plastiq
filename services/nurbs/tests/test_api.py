def test_concurrency_cap_returns_429(monkeypatch):
    # NURBS_MAX_CONCURRENT_JOBS is read inside create_app, so setenv-then-create configures the cap.
    monkeypatch.setenv("NURBS_MAX_CONCURRENT_JOBS", "1")
    release = threading.Event()
    app = create_app(_make_gated_fit_fn(release))

    async def run():
        async with _client(app) as c:
            job_id = None
            try:
                r1 = await c.post("/fit", json=_body())
                assert r1.status_code == 200, r1.text
                job_id = r1.json()["id"]
                # The first job is gated in flight (non-terminal), so it holds the cap of 1.
                r2 = await c.post("/fit", json=_body())
                assert r2.status_code == 429, r2.text
            finally:
                release.set()
                if job_id is not None:
                    await _drain(c, job_id)

    asyncio.run(run())


