"""The NURBS HTTP service, tested end-to-end over the real ASGI app (no mocks) via ``httpx``
``ASGITransport`` on ``asyncio.run`` so background jobs actually progress. Mirrors the
capture/reconstruct/nerf API tests. Gated on ``fastapi``, so it self-skips where the web env is
not installed.

Two layers of coverage:

* **U8.2a — the HTTP shell** (auth / CORS / caps / validation / 404 / 409 / 429 / delete /
  health), driven with an injected ``fit_fn`` (the SPEC-12 §6.1 seam): ``create_app(fit_fn)`` has
  **no import-time dependency** on ``app.pipeline`` — these tests never touch it. A lightweight
  contract-shaped ``fit_fn`` keeps them deterministic and OCCT-free (a ``threading.Event`` gate
  holds a job in flight for the 409 / 429 paths); ``test_submit_poll_result_real_step_end_to_end``
  additionally drives the REAL ``occ_step.surfaces_json_to_step`` through OCCT via an injected fit.
* **U8.2b — the real mesh→fit E2E** (``test_real_*_end_to_end``), driving the PRODUCTION
  dispatcher ``app.main._load_pipeline_fit`` (NOT an injected double): a real base64 GLB fixture
  is submitted, polled to completion, and its ``{ step, surfaces, report }`` fetched — with real
  MLX fitting + real OCCT through the live ASGI service. ``dome.glb`` → an open single-patch STEP
  (``is_solid`` False), ``blob.glb`` → THE GATE: a watertight 6-patch all-NURBS solid that
  re-imports as one closed solid, and a genus-1 ``torus.glb`` fails cleanly (job ``failed`` → 500)
  without killing the service. Gated per-test on ``mlx.core``/``trimesh``/``OCC.Core.Geom``.
"""

import asyncio
import base64
import threading
from pathlib import Path

import pytest

pytest.importorskip("fastapi")
import httpx  # noqa: E402
from httpx import ASGITransport  # noqa: E402

from app.main import _load_pipeline_fit, create_app  # noqa: E402

# Real topology fixtures (committed, generated by tests/fixtures/generate_fixtures.py): dome.glb =
# open disk, blob.glb = closed genus-0, torus.glb = genus-1 (unsupported). Used by the U8.2b E2E.
FIXTURES = Path(__file__).resolve().parent / "fixtures"

# The FR-9 report fields the result must carry (SPEC-12 FR-9 / §6.1).
FR9_REPORT_KEYS = {
    "patches",
    "fitted_patches",
    "faceted_patches",
    "control_points",
    "degree_u",
    "degree_v",
    "iters",
    "chamfer",
    "scd",
    "rms_deviation",
    "max_deviation",
    "fidelity_tol",
    "is_solid",
    "is_valid",
    "mode",
}


def _client(app) -> httpx.AsyncClient:
    return httpx.AsyncClient(transport=ASGITransport(app=app), base_url="http://t")


def _body(**overrides) -> dict:
    """A minimal valid /fit body. ``glb_base64`` is any non-empty string — the shell does not decode
    it (GLB parsing is the injected pipeline's job); here ``fit_fn`` ignores it entirely."""
    return {"glb_base64": "Zm9v", **overrides}  # "foo"


def _glb_body(name: str, **overrides) -> dict:
    """A /fit body carrying a REAL base64-encoded fixture GLB (``dome.glb``/``blob.glb``/
    ``torus.glb``) — for the U8.2b E2E, where the production dispatcher actually decodes and fits it."""
    glb_b64 = base64.b64encode((FIXTURES / name).read_bytes()).decode("ascii")
    return {"glb_base64": glb_b64, **overrides}


def _contract_result(payload: dict) -> dict:
    """A contract-shaped (all-15-FR-9-keys) result that echoes the request params — no OCCT. Lets the
    transport tests assert the body flowed through ``fit_fn`` (``iters``/``mode``) without pythonocc."""
    report = {k: 0 for k in FR9_REPORT_KEYS}
    report.update(iters=payload["iters"], mode=payload["mode"], fidelity_tol=payload["fidelity_tol"])
    return {
        "step": "ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\nENDSEC;\nEND-ISO-10303-21;\n",
        "surfaces": {"surfaces": []},
        "report": report,
    }


def _make_gated_fit_fn(release: threading.Event):
    """A ``fit_fn`` that blocks (in the ``to_thread`` worker) until ``release`` is set, so a job can be
    held provably in flight for the 409 (result-before-done) and 429 (concurrency-cap) paths."""

    def fit_fn(payload: dict) -> dict:
        if not release.wait(timeout=10.0):
            raise TimeoutError("gated fit_fn was never released")
        return _contract_result(payload)

    return fit_fn


async def _drain(c: httpx.AsyncClient, job_id: str, tries: int = 400, delay: float = 0.02) -> str:
    """Poll status until the job is terminal (keeps worker threads from lingering after a test)."""
    state = "queued"
    for _ in range(tries):
        state = (await c.get(f"/jobs/{job_id}/status")).json()["state"]
        if state in ("completed", "failed"):
            break
        await asyncio.sleep(delay)
    return state


