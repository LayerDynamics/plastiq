def test_real_dome_open_end_to_end():
    """dome.glb (OPEN) through the LIVE service: submit → poll → a real single-patch STEP.

    ``iters=0`` is pinned for a DETERMINISTIC result — open-mode ``iters>0`` refine has a known
    thin-margin improvement property being investigated separately, so the E2E stays at pure LSQ
    (``grid=8`` matches the proven open pipeline; dome's 7-vertex boundary arcs interpolate there).
    """
    pytest.importorskip("mlx.core")
    pytest.importorskip("trimesh")
    pytest.importorskip("OCC.Core.Geom")

    app = create_app(_load_pipeline_fit)  # the production dispatcher, not an injected double

    async def run():
        async with _client(app) as c:
            r = await c.post("/fit", json=_glb_body("dome.glb", mode="auto", grid=8, iters=0))
            assert r.status_code == 200, r.text
            assert r.json()["state"] in ("queued", "running")
            job_id = r.json()["id"]

            state = await _drain(c, job_id, tries=2000, delay=0.05)
            status = (await c.get(f"/jobs/{job_id}/status")).json()
            assert state == "completed", f"dome job ended in {state}: {status}"

            result = await c.get(f"/jobs/{job_id}/result")
            assert result.status_code == 200, result.text
            body = result.json()
            # Real OCCT STEP: exactly one B-spline face (the single open patch).
            assert body["step"].count("B_SPLINE_SURFACE_WITH_KNOTS") == 1, body["step"]
